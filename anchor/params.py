def make_T(dur_s):
    """Сетка якорей под РЕАЛЬНУЮ длину пары: [T0, dur) с шагом STEP. Верх = dur (не dur−T0):
    зрению нужно лишь НАЛИЧИЕ кадров (без 5с-окна) → покрываем хвост целиком; у band/multispec
    хвостовые окна, выходящие за дорожку, гасит леаф-кламп (o=NaN/w=0). Прод строит сетку от
    длины (любая длительность, не только ≤ ~23 мин); глобал T ниже — лишь дефолт стендов."""
    last = max(T0 + STEP, float(dur_s))
    return np.arange(T0, last, STEP)


